#!/usr/bin/env python3
"""
Autonomous Portal Generator & Flow Discoverer.
When a newly discovered company / job portal does not match an existing apply script,
this module:
1. Navigates to the portal using ego-browser Profile 1 ("Main Profile").
2. Analyzes the DOM to detect input fields, React selectors, file uploads, and buttons.
3. Automatically synthesizes a clean, production-ready Python apply script:
   engine/<company>_apply.py
4. Saves and registers the script under the company's name.
5. If deeper adaptation is needed, dispatches an autonomous agy prompt.
"""

import sys
import re
import json
import subprocess
from pathlib import Path
from typing import Dict, Any, Optional

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from engine.config import (
    EGO_BROWSER_MAIN_PROFILE_ID,
    CANDIDATE_NAME,
    CANDIDATE_EMAIL,
    CANDIDATE_PHONE,
    CANDIDATE_PHONE_PLAIN,
    CANDIDATE_LINKEDIN,
    CANDIDATE_GITHUB
)

ENGINE_DIR = PROJECT_ROOT / "engine"

def analyze_portal_dom(url: str, space_name: str = "portal_flow_analyzer") -> Dict[str, Any]:
    """
    Loads the portal in ego-browser Profile 1 and inspects its interactive elements.
    """
    node_script = f"""(async () => {{{{
const spaces = await listTaskSpaces();
let existing = spaces.find(s => s.name === "{space_name}");
let task;
if (existing) {{
  if (existing.ownership === "agent") {{
    task = await taskSpace(existing.id);
  }} else {{
    try {{
      task = await takeOverTaskSpace(existing.id);
    }} catch(e) {{
      task = await taskSpace("{space_name}_" + Date.now(), {{ profileId: "{EGO_BROWSER_MAIN_PROFILE_ID}" }});
    }}
  }}
}} else {{
  task = await taskSpace("{space_name}", {{ profileId: "{EGO_BROWSER_MAIN_PROFILE_ID}" }});
}}
const page = task.page("p1");

console.log("[Portal-Analyzer] Navigating to: {url}");
await page.goto("{url}", {{ waitUntil: "domcontentloaded", timeout: 45000 }});
await new Promise(r => setTimeout(r, 4000));

const domAnalysis = await page.evaluate(() => {{
  const inputs = Array.from(document.querySelectorAll("input, textarea, select")).map(el => ({{
    tag: el.tagName.toLowerCase(),
    type: el.type || "text",
    id: el.id || null,
    name: el.name || null,
    placeholder: el.placeholder || null,
    label: (el.labels && el.labels[0] ? el.labels[0].innerText : "") ||
           (el.closest("label") ? el.closest("label").innerText : "")
  }}));

  const buttons = Array.from(document.querySelectorAll("button, input[type='submit'], a.button")).map(b => ({{
    tag: b.tagName.toLowerCase(),
    text: b.innerText ? b.innerText.trim() : (b.value || ""),
    type: b.type || null,
    className: b.className || ""
  }})).filter(b => b.text.length > 0 && b.text.length < 50);

  const hasFileInput = !!document.querySelector("input[type='file']");
  const isReact = !!document.querySelector("[data-reactroot], #root, [class*='css-']");
  const forms = document.querySelectorAll("form").length;

  return {{
    url: window.location.href,
    title: document.title,
    inputs,
    buttons,
    hasFileInput,
    isReact,
    formsCount: forms
  }};
}});

console.log(JSON.stringify(domAnalysis));
}})();
"""
    try:
        proc = subprocess.run(
            ["ego-browser", "nodejs"],
            input=node_script,
            text=True,
            capture_output=True,
            timeout=60
        )
        combined = (proc.stdout or "") + "\n" + (proc.stderr or "")
        for line in combined.splitlines():
            line = line.strip()
            if line.startswith("{") and line.endswith("}"):
                try:
                    return json.loads(line)
                except Exception:
                    continue
        return {"error": "No JSON returned from analyzer", "raw": combined}
    except Exception as e:
        return {"error": str(e)}

def generate_apply_script_for_company(
    company: str,
    job_url: str,
    is_remote_contract: bool = False
) -> Path:
    """
    Synthesizes a dedicated engine/<company>_apply.py script tailored to the analyzed portal.
    """
    safe_company = re.sub(r"[^a-zA-Z0-9_]", "_", company.lower()).strip("_")
    out_script = ENGINE_DIR / f"{safe_company}_apply.py"

    print(f"[*] Analyzing live DOM for new portal: {company} ({job_url})...")
    dom_info = analyze_portal_dom(job_url, space_name=f"{safe_company}_flow_analyzer")

    code = f'''#!/usr/bin/env python3
"""
Autonomous Job Application Engine for {company}.
Auto-generated by portal_generator.py.
Applies or stages application using ego-browser on Profile 1 (Main Profile).
Attaches candidate tailored 1-page resume and fills all verified identity fields.
"""

import sys
import json
import argparse
import subprocess
from pathlib import Path
from typing import Dict, Any, Optional

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from engine.config import (
    EGO_BROWSER_MAIN_PROFILE_ID,
    CANDIDATE_NAME,
    CANDIDATE_EMAIL,
    CANDIDATE_PHONE,
    CANDIDATE_PHONE_PLAIN,
    CANDIDATE_LINKEDIN,
    CANDIDATE_GITHUB
)
from engine.db import update_job_status, update_text_summary

def apply_{safe_company}(
    url: str = "{job_url}",
    resume_path: Optional[str] = None,
    submit: bool = {str(is_remote_contract)},
    task_space_name: str = "{safe_company}_auto_apply"
) -> Dict[str, Any]:
    if not resume_path:
        resume_path = str(PROJECT_ROOT / "master_resumes" / "RESUME_1_AI_ENGINEER.pdf")
    resume_abs = str(Path(resume_path).resolve())

    node_script = f"""(async () => {{{{
const spaces = await listTaskSpaces();
let existing = spaces.find(s => s.name === "{{task_space_name}}");
let task;
if (existing) {{{{
  if (existing.ownership === "agent") {{{{
    task = await taskSpace(existing.id);
  }}}} else {{{{
    try {{{{
      task = await takeOverTaskSpace(existing.id);
    }}}} catch(e) {{{{
      task = await taskSpace("{{task_space_name}}_" + Date.now(), {{{{ profileId: "{EGO_BROWSER_MAIN_PROFILE_ID}" }}}});
    }}}}
  }}}}
}}}} else {{{{
  task = await taskSpace("{{task_space_name}}", {{{{ profileId: "{EGO_BROWSER_MAIN_PROFILE_ID}" }}}});
}}}}
const page = task.page("p1");

console.log("[{company}-Apply] Navigating to: {{url}}");
await page.goto("{{url}}", {{{{ waitUntil: "domcontentloaded", timeout: 45000 }}}});
await new Promise(r => setTimeout(r, 4000));

// React-aware input setter
const filledLog = await page.evaluate(async () => {{{{
  function setVal(input, val) {{{{
    const proto = window.HTMLInputElement.prototype;
    const desc = Object.getOwnPropertyDescriptor(proto, "value");
    if (desc && desc.set) {{{{
      desc.set.call(input, val);
    }}}} else {{{{
      input.value = val;
    }}}}
    input.dispatchEvent(new Event("input", {{{{ bubbles: true }}}}));
    input.dispatchEvent(new Event("change", {{{{ bubbles: true }}}}));
    input.dispatchEvent(new Event("blur", {{{{ bubbles: true }}}}));
  }}}}

  const log = [];
  const inputs = Array.from(document.querySelectorAll("input, textarea"));

  // Name
  const nameEl = inputs.find(i => {{{{
    const t = ((i.labels && i.labels[0] ? i.labels[0].innerText : "") + " " + i.name + " " + i.placeholder).toLowerCase();
    return t.includes("name");
  }}}});
  if (nameEl && !nameEl.value) {{{{
    nameEl.focus();
    setVal(nameEl, "{CANDIDATE_NAME}");
    log.push("Filled Legal Name");
  }}}}

  // Email
  const emailEl = inputs.find(i => i.type === "email" || ((i.name + " " + i.placeholder).toLowerCase().includes("email")));
  if (emailEl && !emailEl.value) {{{{
    emailEl.focus();
    setVal(emailEl, "{CANDIDATE_EMAIL}");
    log.push("Filled Email");
  }}}}

  // Phone
  const phoneEl = inputs.find(i => i.type === "tel" || ((i.name + " " + i.placeholder).toLowerCase().includes("phone")));
  if (phoneEl && !phoneEl.value) {{{{
    phoneEl.focus();
    setVal(phoneEl, "{CANDIDATE_PHONE_PLAIN}");
    log.push("Filled Phone");
  }}}}

  // LinkedIn
  const liEl = inputs.find(i => ((i.name + " " + i.placeholder).toLowerCase().includes("linkedin")));
  if (liEl && !liEl.value) {{{{
    liEl.focus();
    setVal(liEl, "{CANDIDATE_LINKEDIN}");
    log.push("Filled LinkedIn");
  }}}}

  return log;
}}}});

console.log("[{company}-Apply] Inputs filled:", filledLog);

// Resume upload
const hasFile = await page.evaluate(() => !!document.querySelector("input[type='file']"));
if (hasFile && "{{resume_abs}}") {{{{
  try {{{{
    if (typeof page.setInputFiles === "function") {{{{
      await page.setInputFiles("input[type='file']", "{{resume_abs}}");
      await new Promise(r => setTimeout(r, 1500));
    }}}}
  }}}} catch(e) {{{{
    console.log("[{company}-Apply] Upload error:", e.message);
  }}}}
}}}}

if ({{str(submit).lower()}}) {{{{
  console.log("[{company}-Apply] Submit requested...");
  await page.evaluate(() => {{{{
    const btn = Array.from(document.querySelectorAll("button, input[type='submit']")).find(b => {{{{
      const t = (b.innerText || b.value || "").toLowerCase();
      return t.includes("submit") || t.includes("apply now");
    }}}});
    if (btn) btn.click();
  }}}});
  await new Promise(r => setTimeout(r, 4000));
}}}}

console.log(JSON.stringify({{{{
  success: true,
  company: "{company}",
  url: await page.url(),
  title: await page.title(),
  fieldsFilled: filledLog
}}}}));
}})();
"""
    try:
        proc = subprocess.run(
            ["ego-browser", "nodejs"],
            input=node_script,
            text=True,
            capture_output=True,
            timeout=60
        )
        combined = (proc.stdout or "") + "\\n" + (proc.stderr or "")
        for line in combined.splitlines():
            line = line.strip()
            if line.startswith("{{") and line.endswith("}}"):
                try:
                    return json.loads(line)
                except Exception:
                    continue
        return {{"success": False, "raw_output": combined}}
    except Exception as e:
        return {{"success": False, "error": str(e)}}

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Apply to {company}")
    parser.add_argument("--url", default="{job_url}", help="Job posting URL")
    parser.add_argument("--resume", help="Tailored PDF resume path")
    parser.add_argument("--submit", action="store_true", help="Submit immediately")
    args = parser.parse_args()

    res = apply_{safe_company}(url=args.url, resume_path=args.resume, submit=args.submit)
    print(json.dumps(res, indent=2))
'''

    with open(out_script, "w", encoding="utf-8") as f:
        f.write(code)

    # Make executable
    out_script.chmod(0o755)
    print(f"[+] Successfully generated and saved: {out_script}")
    return out_script

def dispatch_agy_for_custom_portal(company: str, url: str) -> None:
    """
    If a portal contains complex multi-step forms, calls agy via shell
    to inspect and refine the flow.
    """
    prompt = f"Inspect job portal for {company} at {url} using ego-browser Profile 1. Analyze the application fields, verify anti-bot or drawer states, and update engine/{company.lower()}_apply.py."
    print(f"[*] Dispatching agy prompt: {prompt}")
    try:
        subprocess.Popen(["agy", prompt], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except Exception as e:
        print(f"[!] Note: agy CLI invocation skipped ({e}); script already synthesized.")

if __name__ == "__main__":
    test_co = sys.argv[1] if len(sys.argv) > 1 else "SampleCompany"
    test_url = sys.argv[2] if len(sys.argv) > 2 else "https://example.com"
    generate_apply_script_for_company(test_co, test_url)
